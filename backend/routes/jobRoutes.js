const express = require("express");

const router = express.Router();

// ============================================================
// CONTROLLERS
// ============================================================

const {
    getJobs,
    getJobById,
    createJob,
    getMyRecruiterJobs,
    updateJob,
    deleteJob,
} = require("../controllers/jobController");

// ============================================================
// MIDDLEWARE
// ============================================================

const { protect } = require("../middleware/authMiddleware");

// ============================================================
// PUBLIC JOB ROUTES
// ============================================================

// ------------------------------------------------------------
// GET ALL JOBS
// GET /api/jobs
// ------------------------------------------------------------

router.get(
    "/",
    getJobs
);

// ------------------------------------------------------------
// GET SINGLE JOB
// GET /api/jobs/:jobId
// ------------------------------------------------------------

router.get(
    "/:jobId",
    getJobById
);

// ============================================================
// RECRUITER JOB ROUTES
// ============================================================

// ------------------------------------------------------------
// GET RECRUITER'S OWN JOBS
// GET /api/jobs/recruiter/my
// ------------------------------------------------------------

router.get(
    "/recruiter/my",
    protect,
    getMyRecruiterJobs
);

// ------------------------------------------------------------
// CREATE JOB
// POST /api/jobs
// ------------------------------------------------------------

router.post(
    "/",
    protect,
    createJob
);

// ------------------------------------------------------------
// UPDATE JOB
// PUT /api/jobs/:jobId
// ------------------------------------------------------------

router.put(
    "/:jobId",
    protect,
    updateJob
);

// ------------------------------------------------------------
// DELETE JOB
// DELETE /api/jobs/:jobId
// ------------------------------------------------------------

router.delete(
    "/:jobId",
    protect,
    deleteJob
);

// ============================================================
// EXPORT ROUTER
// ============================================================

module.exports = router;